import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';

class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = [
    Locale('fr'),
    Locale('en'),
    Locale('de'),
    Locale('nl'),
    Locale('es'),
  ];

  static const delegate = _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    final localizations = Localizations.of<AppLocalizations>(
      context,
      AppLocalizations,
    );
    return localizations ?? const AppLocalizations(Locale('fr'));
  }

  String get languageCode {
    final code = locale.languageCode.toLowerCase();
    return _translations.containsKey(code) ? code : 'fr';
  }

  String text(String key) {
    return _translations[languageCode]?[key] ??
        _translations['fr']?[key] ??
        key;
  }

  String format(String key, Map<String, Object?> values) {
    var value = text(key);
    for (final entry in values.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return value;
  }

  String requiredField(String field) =>
      format('requiredField', {'field': field});

  String cartUpdateFailed(Object error) {
    return format('cartUpdateFailed', {'error': error});
  }

  String missingOrderAmount(String amount) {
    return format('missingOrderAmount', {'amount': amount});
  }

  String orderConfirmedBy(String company) {
    return format('orderConfirmedBy', {'company': company});
  }

  String genericError(Object error) => format('genericError', {'error': error});

  String passwordUpdateFailed(Object error) {
    return format('passwordUpdateFailed', {'error': error});
  }
}

extension AppLocalizationsX on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return AppLocalizations.supportedLocales.any(
      (supported) => supported.languageCode == locale.languageCode,
    );
  }

  @override
  Future<AppLocalizations> load(Locale locale) {
    return SynchronousFuture(AppLocalizations(locale));
  }

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) {
    return false;
  }
}

